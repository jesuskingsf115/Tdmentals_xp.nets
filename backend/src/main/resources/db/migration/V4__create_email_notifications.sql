
-- Cria a tabela de notificações por e-mail
CREATE TABLE email_notifications (
                                     id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                     user_id BIGINT NOT NULL,
                                     alert_id BIGINT NOT NULL,
                                     sent_at TIMESTAMP,
                                     status VARCHAR(20) NOT NULL DEFAULT 'PENDING',

                                     CONSTRAINT fk_email_notifications_user
                                         FOREIGN KEY (user_id)
                                             REFERENCES users(id),

                                     CONSTRAINT fk_email_notifications_alert
                                         FOREIGN KEY (alert_id)
                                             REFERENCES alerts(id)
);

-- Índice para buscar notificações pelo usuário
CREATE INDEX idx_email_notifications_user_id
    ON email_notifications(user_id);

-- Índice para buscar notificações pelo alerta
CREATE INDEX idx_email_notifications_alert_id
    ON email_notifications(alert_id);
